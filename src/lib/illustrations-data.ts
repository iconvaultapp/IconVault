export const illustrationUrl = (slug: string, theme: "light" | "dark"): string =>
  `/illustrations/${theme}/${encodeURIComponent(slug)}.svg`;

/** The Flowbite brand-blue ramp, deep -> pale. Recolouring swaps the whole
 *  ramp so shading stays coherent instead of flattening to one colour. */
const BRAND_RAMP = ["#1555e2", "#2563eb", "#9ab7f6", "#c8d8fa", "#d6e2fb"] as const;
export const DEFAULT_ILLUSTRATION_COLOR = "#2563eb";

const hexToRgb = (hex: string): [number, number, number] => {
  const n = parseInt(hex.replace("#", ""), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};
const rgbToHex = (r: number, g: number, b: number): string =>
  "#" + [r, g, b].map((v) => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, "0")).join("");
/** amt 0 = colour itself, 1 = white. */
const mixWhite = (hex: string, amt: number): string => {
  const [r, g, b] = hexToRgb(hex);
  return rgbToHex(r + (255 - r) * amt, g + (255 - g) * amt, b + (255 - b) * amt);
};
/** amt 0 = colour itself, 1 = black. */
const mixBlack = (hex: string, amt: number): string => {
  const [r, g, b] = hexToRgb(hex);
  return rgbToHex(r * (1 - amt), g * (1 - amt), b * (1 - amt));
};

/** Swap the Flowbite blue ramp for the same ramp built from `primary`. */
export const recolorSvg = (svg: string, primary: string): string => {
  const p = primary.toLowerCase();
  if (!/^#[0-9a-f]{6}$/.test(p) || p === DEFAULT_ILLUSTRATION_COLOR) return svg;
  const ramp = [mixBlack(p, 0.18), p, mixWhite(p, 0.58), mixWhite(p, 0.79), mixWhite(p, 0.86)];
  let out = svg;
  BRAND_RAMP.forEach((from, i) => {
    out = out.replace(new RegExp(from, "gi"), ramp[i] as string);
  });
  return out;
};

const rawCache = new Map<string, Promise<string>>();

/** Fetch one illustration's raw SVG markup (session-cached). */
export const loadIllustrationSvg = (slug: string, theme: "light" | "dark"): Promise<string> => {
  const key = `${theme}:${slug}`;
  const hit = rawCache.get(key);
  if (hit) return hit;
  const promise = fetch(illustrationUrl(slug, theme)).then((res) => {
    if (!res.ok) throw new Error(`Illustration missing: ${key}`);
    return res.text();
  });
  rawCache.set(key, promise);
  return promise;
};

/** Set explicit width/height on the root <svg> for downloads. */
export const sizeSvg = (svg: string, px: number): string =>
  svg.replace(/<svg([^>]*)>/i, (_m, attrs: string) => {
    const cleaned = String(attrs).replace(/\s(width|height)="[^"]*"/gi, "");
    return `<svg${cleaned} width="${px}" height="${px}">`;
  });
