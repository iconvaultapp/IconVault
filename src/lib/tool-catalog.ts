/** Live tools of one hub category, in catalog order. */
export function toolsByCategory(categoryId: string): ToolDef[] {
  return LIVE_TOOLS.filter((t) => t.category === categoryId);
}

/** Other live tools, for the "More tools" cross-link section - same category first. */
export function relatedTools(excludeId: string, count = 4): ToolDef[] {
  const self = LIVE_TOOLS.find((t) => t.id === excludeId);
  const others = LIVE_TOOLS.filter((t) => t.id !== excludeId);
  if (self?.category) {
    const same = others.filter((t) => t.category === self.category);
    const rest = others.filter((t) => t.category !== self.category);
    return [...same, ...rest].slice(0, count);
  }
  return others.slice(0, count);
}

